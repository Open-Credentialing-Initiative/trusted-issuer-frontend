#!/usr/bin/env node
// Builds a point-in-time snapshot of every HintValueChanged event for each
// registry, so the app can import a bundled module instead of walking the full
// chain history on every visit. Run again periodically (or in CI) to refresh -
// the hook only needs to fetch blocks newer than `snapshotBlock` at runtime.
//
// Usage: node --env-file=.env scripts/generate-hint-snapshots.mjs

import {createPublicClient, http, parseAbiItem} from "viem";
import {mainnet, sepolia} from "viem/chains";
import {mkdir, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const toCamelCase = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

const HINT_VALUE_CHANGED_ABI_ITEM = parseAbiItem(
  "event HintValueChanged(address indexed namespace, bytes32 indexed list, bytes32 indexed key, bytes32 value)"
);

const REGISTRIES = [
  {name: "stk-int", address: "0x6F68c931d785eee932d29A4419B6e28081bbb597", chain: sepolia, deployBlock: 5409263n},
  {name: "wlt-int", address: "0x9497Bb14906aa6D4241Adf83708891fAe6ba171C", chain: sepolia, deployBlock: 5409274n},
  {name: "pbl-int", address: "0x949AEe13C99Ffd7250DaC5865659DB17744352B9", chain: sepolia, deployBlock: 5409297n},
  {name: "prd", address: "0x962646c54ba9C53aA16f662F50175407681B26f3", chain: mainnet, deployBlock: 19357011n},
];

const BATCH_BLOCKS = 10_000n;
const MAX_RATE_LIMIT_RETRIES = 5;
const OUTPUT_DIR = path.join(__dirname, "..", "lib", "hint-snapshots");

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const isRateLimitError = (e) => /rate limit|too many requests|429/i.test(e?.message ?? String(e));

async function getLogsWithRetry(client, address, fromBlock, toBlock, retries = 0) {
  try {
    return await client.getLogs({address, event: HINT_VALUE_CHANGED_ABI_ITEM, fromBlock, toBlock});
  } catch (e) {
    if (isRateLimitError(e) && retries < MAX_RATE_LIMIT_RETRIES) {
      await sleep(2 ** retries * 250);
      return getLogsWithRetry(client, address, fromBlock, toBlock, retries + 1);
    }
    throw e;
  }
}

function renderModule({name, address, chainId, snapshotBlock, generatedAt, logs}) {
  const logLiterals = logs
    .map((log) => `  {blockNumber: ${log.blockNumber}n, namespace: "${log.namespace}", list: "${log.list}", key: "${log.key}", value: "${log.value}"},`)
    .join("\n");

  return `// Auto-generated by scripts/generate-hint-snapshots.mjs - do not edit by hand.
// Regenerate with: pnpm snapshot:hints

export const registryAddress = "${address}" as const;
export const chainId = ${chainId};
export const snapshotBlock = ${snapshotBlock}n;
export const generatedAt = "${generatedAt}";

export const logs: {blockNumber: bigint, namespace: \`0x\${string}\`, list: \`0x\${string}\`, key: \`0x\${string}\`, value: \`0x\${string}\`}[] = [
${logLiterals}
];
`;
}

function renderIndexModule(registries) {
  const imports = registries
    .map(({name}) => `import * as ${toCamelCase(name)} from "./${name}";`)
    .join("\n");
  const entries = registries
    .map(({name}) => `  [${toCamelCase(name)}.registryAddress]: ${toCamelCase(name)},`)
    .join("\n");

  return `// Auto-generated by scripts/generate-hint-snapshots.mjs - do not edit by hand.
// Regenerate with: pnpm snapshot:hints

${imports}

export type HintSnapshot = {
  registryAddress: \`0x\${string}\`;
  chainId: number;
  snapshotBlock: bigint;
  generatedAt: string;
  logs: {blockNumber: bigint, namespace: \`0x\${string}\`, list: \`0x\${string}\`, key: \`0x\${string}\`, value: \`0x\${string}\`}[];
};

export const HINT_SNAPSHOTS: Record<string, HintSnapshot> = {
${entries}
};
`;
}

async function snapshotRegistry({name, address, chain, deployBlock}) {
  const apiKey = process.env.NEXT_PUBLIC_INFURA_API_KEY;
  if (!apiKey) {
    throw new Error("NEXT_PUBLIC_INFURA_API_KEY is not set");
  }

  const client = createPublicClient({
    chain,
    transport: http(`https://${chain.id === mainnet.id ? "mainnet" : "sepolia"}.infura.io/v3/${apiKey}`),
  });

  const latestBlock = await client.getBlockNumber();
  const logs = [];

  // Every namespace at once (no `args` filter) - the snapshot has to serve any
  // safe/namespace that later loads it, not just one.
  for (let fromBlock = deployBlock; fromBlock <= latestBlock; fromBlock += BATCH_BLOCKS) {
    const toBlock = fromBlock + BATCH_BLOCKS - 1n > latestBlock ? latestBlock : fromBlock + BATCH_BLOCKS - 1n;
    const batchLogs = await getLogsWithRetry(client, address, fromBlock, toBlock);
    console.log(`[${name}] blocks ${fromBlock}-${toBlock}: ${batchLogs.length} logs`);
    logs.push(...batchLogs);
  }

  const moduleSource = renderModule({
    name,
    address,
    chainId: chain.id,
    snapshotBlock: latestBlock.toString(),
    generatedAt: new Date().toISOString(),
    logs: logs.map((log) => ({
      blockNumber: log.blockNumber.toString(),
      namespace: log.args.namespace,
      list: log.args.list,
      key: log.args.key,
      value: log.args.value,
    })),
  });

  await mkdir(OUTPUT_DIR, {recursive: true});
  const outputPath = path.join(OUTPUT_DIR, `${name}.ts`);
  await writeFile(outputPath, moduleSource);
  console.log(`[${name}] wrote ${logs.length} logs up to block ${latestBlock} -> ${outputPath}`);
}

for (const registry of REGISTRIES) {
  await snapshotRegistry(registry);
}

await mkdir(OUTPUT_DIR, {recursive: true});
const indexPath = path.join(OUTPUT_DIR, "index.ts");
await writeFile(indexPath, renderIndexModule(REGISTRIES));
console.log(`wrote snapshot index -> ${indexPath}`);
